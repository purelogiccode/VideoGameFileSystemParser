    private void ReturnCachedHunk()
    {
        if (_cachedHunk.Length > 0)
        {
            ArrayPool<byte>.Shared.Return(_cachedHunk);
            _cachedHunk = [];
        }
    }

    /// <summary>
    /// Reads a single 2048-byte data sector at the specified LBA into the given buffer.
    /// </summary>
    /// <param name="outBuffer">The destination buffer.</param>
    /// <param name="lba">The logical block address.</param>
    /// <param name="outOffset">The buffer write offset.</param>
    /// <returns>true if the sector was read successfully.</returns>
    public bool ReadSector(uint lba, byte[] outBuffer, int outOffset = 0)
    {
        if (!PrepareHunk(lba, out var rawOffset))
            return false;

        var sourceIndex = (int)(rawOffset + SectorHeaderOffset);
        if (sourceIndex + SectorSize > _cachedHunk.Length)
            return false;

        Array.Copy(_cachedHunk, sourceIndex, outBuffer, outOffset, SectorSize);

        if (UnitBytes >= 2352 && _wasScrambled)
        {
            var dataStartInSector = (int)SectorHeaderOffset - (int)SyncOffset;
            for (var i = 0; i < SectorSize; i++)
            {
                var scrambleIdx = dataStartInSector + i;
                if (scrambleIdx >= 0 && scrambleIdx < SectorScramble.Length)
                {
                    outBuffer[outOffset + i] ^= SectorScramble[scrambleIdx];
                }
            }
        }

        return true;
    }

    /// <summary>
    /// Reads a single 2048-byte data sector and returns it as a new byte array.
    /// </summary>
    /// <param name="lba">The logical block address.</param>
    /// <returns>The sector data, or null on failure.</returns>
    public byte[]? ReadSector(uint lba)
    {
        var buffer = new byte[SectorSize];
        if (ReadSector(lba, buffer))
            return buffer;

        return null;
    }

    /// <summary>
    /// Reads a full raw sector (UnitBytes length) at the specified LBA.
    /// </summary>
    /// <param name="rawSector">The raw sector data output on success.</param>
    /// <param name="lba">The logical block address.</param>
    /// <returns>true if the raw sector was read.</returns>
    public bool ReadRawSector(uint lba, out byte[] rawSector)
    {
        rawSector = null!;
        if (!PrepareHunk(lba, out var rawOffset))
            return false;

        var unitBytes = (int)UnitBytes;
        if (rawOffset + unitBytes > _cachedHunk.Length)
            return false;

        rawSector = new byte[unitBytes];
        Array.Copy(_cachedHunk, (int)rawOffset, rawSector, 0, unitBytes);
        return true;
    }

    /// <summary>
    /// Reads the subheader file number from an interleaved CD-XA sector.
    /// </summary>
    /// <param name="lba">The logical block address.</param>
    /// <returns>The file number, or 0xFF if unavailable.</returns>
    internal byte GetSubheaderFileNumber(uint lba)
    {
        if (!PrepareHunk(lba, out var rawOffset))
            return 0xFF;

        var unitBytes = (int)UnitBytes;
        if (unitBytes < 2352)
            return 0xFF;

        var subheaderOffset = (int)rawOffset + 16;
        if (subheaderOffset + 1 > _cachedHunk.Length)
            return 0xFF;

        return _cachedHunk[subheaderOffset];
    }

    private bool PrepareHunk(uint lba, out uint rawOffsetInHunk)
    {
        rawOffsetInHunk = 0;

        var hunkBytes = _chd.HunkBytes;
        if (hunkBytes == 0 || UnitBytes == 0)
            return false;

        var sectorsPerHunk = hunkBytes / UnitBytes;
        if (sectorsPerHunk == 0)
            return false;

        uint chdFrame = 0;

        if (_trackLocked && CurrentTrack != null)
        {
            var relative = (long)lba - CurrentTrack.StartLba;
            if (relative >= 0 && relative < CurrentTrack.Frames)
            {
                chdFrame = CurrentTrack.ChdOffset + (uint)relative;
            }
            else
            {
                return false;
            }
        }
        else
        {
            var found = false;
            var adjustedLba = (uint)(lba + LbaOffset);

            if (CurrentTrack != null && adjustedLba >= CurrentTrack.StartLba &&
                adjustedLba < CurrentTrack.StartLba + CurrentTrack.Frames)
            {
                chdFrame = CurrentTrack.ChdOffset + (adjustedLba - CurrentTrack.StartLba);
                found = true;
            }

            if (!found && Tracks.Count > 0)
            {
                foreach (var track in Tracks)
                {
                    if (adjustedLba >= track.StartLba && adjustedLba < track.StartLba + track.Frames)
                    {
                        chdFrame = track.ChdOffset + (adjustedLba - track.StartLba);
                        CurrentTrack = track;
                        found = true;
                        break;
                    }
                }
            }

            if (!found)
            {
                chdFrame = adjustedLba;
                CurrentTrack = null;
            }
        }

        var hunkNum = chdFrame / sectorsPerHunk;
        var sectorInHunk = chdFrame % sectorsPerHunk;

        var needsSwap = CurrentTrack?.TrackType == "AUDIO";

        if (hunkNum != _cachedHunkNum || _cachedHunkSwapped != needsSwap)
        {
            var buffer = ArrayPool<byte>.Shared.Rent((int)hunkBytes);
            try
            {
                var err = _chd.ReadHunk(hunkNum, buffer);
                if (err != ChdError.Chderrnone)
                {
                    ArrayPool<byte>.Shared.Return(buffer);
                    return false;
                }

                if (needsSwap)
                {
                    var swapped = ArrayPool<byte>.Shared.Rent((int)hunkBytes);
                    for (var i = 0; i + 1 < (int)hunkBytes; i += 2)
                    {
                        swapped[i] = buffer[i + 1];
                        swapped[i + 1] = buffer[i];
                    }

                    ArrayPool<byte>.Shared.Return(buffer);
                    ReturnCachedHunk();
                    _cachedHunk = swapped;
                }
                else
                {
                    ReturnCachedHunk();
                    _cachedHunk = buffer;
                }
            }
            catch
            {
                ArrayPool<byte>.Shared.Return(buffer);
                throw;
            }

            _cachedHunkNum = hunkNum;
            _cachedHunkSwapped = needsSwap;
            _isOffsetDetected = false;
            _wasScrambled = false;
        }

        rawOffsetInHunk = sectorInHunk * UnitBytes;

        var trackIdx = CurrentTrack?.Index ?? -1;

        if (_globalOffsetLocked)
        {
            SectorHeaderOffset = _globalSectorHeaderOffset;
            _wasScrambled = _globalWasScrambled;
        }
        else if (trackIdx >= 0 && _trackOffsetCache.TryGetValue(trackIdx, out var precached))
        {
            SectorHeaderOffset = precached.Offset;
            _wasScrambled = precached.Scrambled;
        }
        else if (!_isOffsetDetected || hunkNum != _offsetDetectedHunk || CurrentTrack != _offsetDetectedTrack || trackIdx != _lastTrackIdx)
        {
            if (UnitBytes >= 2352)
            {
                DetectSectorOffset(rawOffsetInHunk, trackIdx);
            }
            else
            {
                SyncOffset = 0;
                SectorHeaderOffset = 0;
            }

            _isOffsetDetected = true;
            _offsetDetectedHunk = hunkNum;
            _offsetDetectedTrack = CurrentTrack;
            _lastTrackIdx = trackIdx;
        }

        return true;
    }

    private void DetectSectorOffset(uint rawOffsetInHunk, int trackIdx)
    {
        var searchRange = (int)Math.Min(128, UnitBytes - 16);
        var foundSyncOffset = -1;

        for (var i = 0; i < searchRange; i++)
        {
            if ((int)(rawOffsetInHunk + i + 12) > _cachedHunk.Length)
                break;

            var match = true;
            for (var j = 0; j < 12; j++)
            {
                if (_cachedHunk[rawOffsetInHunk + i + j] != SyncPattern[j])
                {
                    match = false;
                    break;
                }
            }

            if (match)
            {
                foundSyncOffset = i;
                break;
            }
        }

        if (foundSyncOffset >= 0)
        {
            var absoluteSync = rawOffsetInHunk + (uint)foundSyncOffset;
            var modeByte = _cachedHunk[absoluteSync + 15];
            var isMode2 = modeByte == 2;

            if (!isMode2 && modeByte != 1 && UnitBytes >= 2352)
            {
                var descrambled = (byte)(modeByte ^ SectorScramble[15]);
                switch (descrambled)
                {
                    case 2:
                        isMode2 = true;
                        _wasScrambled = true;
                        break;
                    case 1:
                        _wasScrambled = true;
                        break;
                }
            }

            SyncOffset = (uint)foundSyncOffset;
            SectorHeaderOffset = (uint)(foundSyncOffset + (isMode2 ? 24 : 16));
            _trackOffsetCache[trackIdx] = (SectorHeaderOffset, _wasScrambled);
            _globalOffsetLocked = true;
            _globalSectorHeaderOffset = SectorHeaderOffset;
            _globalWasScrambled = _wasScrambled;
        }
        else
        {
            var isCooked = false;
            uint cookedOffset = 0;
            uint[] candidateOffsets = [0, 16, 24, 96, 112, 120];

            foreach (var candidate in candidateOffsets)
            {
                if (rawOffsetInHunk + candidate + 16 > _cachedHunk.Length)
                    continue;

                var checkOff = (int)(rawOffsetInHunk + candidate);
                if (CheckSignature(checkOff, "CD001", 1) ||
                    CheckSignature(checkOff, "CDROM", 9) ||
                    CheckSignature(checkOff, "BE001", 1))
                {
                    isCooked = true;
                    cookedOffset = candidate;
                    break;
                }

                byte[] operaMagic = [0x01, 0x5A, 0x5A, 0x5A, 0x5A, 0x5A, 0x01];
                var operaMatch = true;
                for (var k = 0; k < 7; k++)
                {
                    if (_cachedHunk[checkOff + k] != operaMagic[k])
                    {
                        operaMatch = false;
                        break;
                    }
                }

                if (operaMatch)
                {
                    isCooked = true;
                    cookedOffset = candidate;
                    break;
                }
            }

            if (isCooked)
            {
                SyncOffset = cookedOffset;
                SectorHeaderOffset = cookedOffset;
                _trackOffsetCache[trackIdx] = (SectorHeaderOffset, false);
                _globalOffsetLocked = true;
                _globalSectorHeaderOffset = SectorHeaderOffset;
                _globalWasScrambled = false;
            }
            else
            {
                var fallbackOffset = GetSectorDataOffset(CurrentTrack);
                var fallbackIsZero = true;
                if (fallbackOffset > 0 && (int)(rawOffsetInHunk + fallbackOffset + 64) <= _cachedHunk.Length)
                {
                    for (var z = 0; z < 64; z++)
                    {
                        if (_cachedHunk[rawOffsetInHunk + fallbackOffset + z] != 0)
                        {
                            fallbackIsZero = false;
                            break;
                        }
                    }
                }

                if (fallbackIsZero || (fallbackOffset > 0 && (int)(rawOffsetInHunk + 2) <= _cachedHunk.Length &&
                                       HasFilesystemSignature(rawOffsetInHunk)))
                {
                    SyncOffset = 0;
                    SectorHeaderOffset = 0;
                    _globalOffsetLocked = true;
                    _globalSectorHeaderOffset = 0;
                    _globalWasScrambled = false;
                }
                else
                {
                    SyncOffset = fallbackOffset;
                    SectorHeaderOffset = fallbackOffset;
                }
            }
        }
    }

    private bool CheckSignature(int offset, string signature, int offsetInSignature)
    {
        var sig = Encoding.ASCII.GetBytes(signature);
        if (offset + offsetInSignature + sig.Length > _cachedHunk.Length)
            return false;

        for (var i = 0; i < sig.Length; i++)
        {
            if (_cachedHunk[offset + offsetInSignature + i] != sig[i])
                return false;
        }

        return true;
    }

    private bool HasFilesystemSignature(uint rawOffsetInHunk)
    {
        // Check for HFS/HFS+ signatures at various byte offsets within the sector.
        // Different disc dumps have different header sizes before the actual data.
        for (var off = 0; off <= 32; off += 2)
        {
            var absOff = (int)rawOffsetInHunk + off;
            if (absOff + 2 > _cachedHunk.Length) break;

            var b0 = _cachedHunk[absOff];
            var b1 = _cachedHunk[absOff + 1];

            switch (b0)
            {
                // HFS boot block "LK"
                case 0x4C when b1 == 0x4B:
                // HFS MDB "BD"
                case 0x42 when b1 == 0x44:
                // HFS+ volume header "HX"
                case 0x48 when b1 == 0x58:
                // HFS+ volume header "H+"
                case 0x48 when b1 == 0x2B:
                // Apple Partition Map "ER"
                case 0x45 when b1 == 0x52:
                    return true;
            }

            // HFS MDB "BD" at byte 1024 from data start
            var mdbOff = absOff + 1024;
            if (mdbOff + 2 <= _cachedHunk.Length)
            {
                if (_cachedHunk[mdbOff] == 0x42 && _cachedHunk[mdbOff + 1] == 0x44) return true;
                if (_cachedHunk[mdbOff] == 0x48 && _cachedHunk[mdbOff + 1] == 0x58) return true;
                if (_cachedHunk[mdbOff] == 0x48 && _cachedHunk[mdbOff + 1] == 0x2B) return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Returns the appropriate sector data offset for a track.
    /// </summary>
    /// <param name="track">The track to evaluate.</param>
    /// <returns>16 for MODE1, 24 for MODE2/CDI, 0 for audio.</returns>
    public static uint GetSectorDataOffset(TrackInfo? track)
    {
        if (track is null) return 16;
        if (!track.IsDataTrack) return 0;
        if (track.TrackType.Contains("MODE2") || track.TrackType.Contains("MODE_2")) return 24;
        if (track.TrackType.Contains("CDI")) return 24;

        return 16;
    }

    /// <summary>
    /// Parses track metadata from the CHD and computes LBA start positions.
    /// </summary>
    /// <param name="unitBytes">The sector size.</param>
    /// <param name="chd">The opened ChdFile.</param>
    /// <returns>A list of TrackInfo with computed LBA positions.</returns>
    internal static List<TrackInfo> ParseTracksWithLba(ChdFile chd, uint unitBytes)
    {
        var tracks = new List<TrackInfo>();
        var metadata = chd.Metadata;

        var hasTrackMetadata = false;

        foreach (var entry in metadata)
        {
            var tag = entry.Tag;
            if (tag.Length < 4) continue;

            var t0 = tag[0];
            var t1 = tag[1];
            var t2 = tag[2];
            var t3 = tag[3];

            var isTrackMeta = t0 == 'C' && t1 == 'H' &&
                              ((t2 == 'T' && t3 is '2' or 'R') || (t2 == 'G' && t3 is 'D' or 'T'));

            var metaText = entry.GetText();
            if (!isTrackMeta || string.IsNullOrEmpty(metaText))
                continue;

            hasTrackMetadata = true;
            var trackIndex = tracks.Count + 1;

            var parsed = TryParseTrackMetadata(metaText, out var typeStr,
                out var frames, out var pregap, out var postgap);

            if (!parsed || frames == 0)
                continue;

            tracks.Add(new TrackInfo
            {
                Index = trackIndex,
                Frames = frames,
                Pregap = pregap,
                Postgap = postgap,
                TrackType = typeStr,
                IsDataTrack = typeStr.Contains("MODE") || typeStr.Contains("CDI"),
                Metadata = metaText
            });
        }

        if (!hasTrackMetadata || tracks.Count == 0)
            return tracks;

        var isGdrom = false;
        foreach (var entry in metadata)
        {
            var tag = entry.Tag;
            if (tag.Length < 4) continue;

            var t0 = tag[0];
            var t1 = tag[1];
            var t2 = tag[2];
            var t3 = tag[3];

            if (t0 == 'C' && t1 == 'H' && t2 == 'G' && t3 is 'D' or 'T')
            {
                isGdrom = true;
                break;
            }
        }

        if (!isGdrom)
        {
            foreach (var t in tracks)
            {
                if (t.Metadata.Contains("PAD:"))
                {
                    isGdrom = true;
                    break;
                }
            }
        }

        if (!isGdrom && tracks.Count >= 3)
        {
            uint totalFrames = 0;
            foreach (var t in tracks)
            {
                totalFrames += t.Frames;
            }

            if (totalFrames is >= 500000 and <= 560000)
            {
                isGdrom = true;
            }
        }

        uint currentFileFrame = 0;
        uint currentLogicalLba = 150;
        const uint gdHighDensityLba = 45000;

        for (var i = 0; i < tracks.Count; i++)
        {
            var track = tracks[i];
            var trackNum = i + 1;

            if (isGdrom && trackNum >= 3 && currentLogicalLba < gdHighDensityLba)
            {
                currentLogicalLba = gdHighDensityLba;
            }

            track.StartLba = currentLogicalLba;
            track.ChdOffset = currentFileFrame;

            // NOTE: The pregap frames are intentionally NOT added to the track's
            // file offset (ChdOffset) or StartLba. chdman stores the pregap
            // sectors as part of the track itself (FRAMES already includes them,
            // as silence before the track data), so the track's chunk in the CHD
            // begins at the pregap. Adding Pregap here shifted every subsequent
            // track by the pregap length (150 frames = 2 s for Neo Geo CD) and
            // pushed the last track past the end of the CHD file. The old C++
            // CHDFileExplorer did not add the pregap either; CUE generation
            // exposes it via INDEX 00/INDEX 01. Consumers that need to skip the
            // pregap (e.g. WAV export) must start reading at StartLba + Pregap.
            currentLogicalLba += track.Frames;
            var padded = (track.Frames + 3) / 4 * 4;
            currentFileFrame += padded;
        }

        CorrectStartLbaFromMsf(chd, tracks, unitBytes);

        foreach (var track in tracks)
        {
            if (!track.IsDataTrack && track is { TrackType: "AUDIO", Frames: > 16 } && unitBytes > 0)
            {
                var sectorsPerHunk = chd.HunkBytes / unitBytes;
                if (sectorsPerHunk > 0)
                {
                    var hunkNum = track.ChdOffset / sectorsPerHunk;
                    var offsetInHunk = track.ChdOffset % sectorsPerHunk * unitBytes;

                    var firstHunk = new byte[chd.HunkBytes];
                    if (chd.ReadHunk(hunkNum, firstHunk) == ChdError.Chderrnone &&
                        (int)(offsetInHunk + 12) <= firstHunk.Length)
                    {
                        var swappedSync = new byte[12];
                        for (var j = 0; j < 12; j++)
                        {
                            swappedSync[j] = firstHunk[offsetInHunk + (j ^ 1)];
                        }

                        var match = true;
                        for (var j = 0; j < 12; j++)
                        {
                            if (swappedSync[j] != SyncPattern[j])
                            {
                                match = false;
                                break;
                            }
                        }

                        if (match)
                        {
                            track.IsDataTrack = true;
                        }
                    }
                }
            }
        }

        return tracks;
    }

    private static bool TryParseTrackMetadata(string metadata, out string typeStr,
        out uint frames, out uint pregap, out uint postgap)
    {
        var parts = metadata.Split(' ');
        var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var part in parts)
        {
            var colonIdx = part.IndexOf(':');
            if (colonIdx > 0)
            {
                var key = part[..colonIdx];
                var value = part[(colonIdx + 1)..];
                map[key] = value;
            }
        }

        typeStr = map.GetValueOrDefault("TYPE", "");
        _ = uint.TryParse(map.GetValueOrDefault("FRAMES", "0"), out frames);
        _ = uint.TryParse(map.GetValueOrDefault("PREGAP", "0"), out pregap);
        _ = uint.TryParse(map.GetValueOrDefault("POSTGAP", "0"), out postgap);

        return frames > 0;
    }

    private static void CorrectStartLbaFromMsf(ChdFile chd, List<TrackInfo> tracks, uint unitBytes)
    {
        if (unitBytes < 2352) return;

        var sectorsPerHunk = chd.HunkBytes / unitBytes;
        if (sectorsPerHunk == 0) return;

        var hunkBuf = new byte[chd.HunkBytes];
        foreach (var track in tracks)
        {
            var startFrame = track.ChdOffset;
            var scanLimit = Math.Min(sectorsPerHunk, 32u);

            var found = false;
            for (uint scan = 0; scan < scanLimit; scan++)
            {
                var frame = startFrame + scan;
                var hunkNum = frame / sectorsPerHunk;
                var sectorInHunk = frame % sectorsPerHunk;

                if (chd.ReadHunk(hunkNum, hunkBuf) != ChdError.Chderrnone)
                    continue;

                var offset = (int)(sectorInHunk * unitBytes);
                if (offset + 16 > hunkBuf.Length) continue;

                if (hunkBuf[offset] != 0x00 || hunkBuf[offset + 1] != 0xFF)
                    continue;

                var minute = BcdToByte(hunkBuf[offset + 12]);
                var second = BcdToByte(hunkBuf[offset + 13]);
                var frameVal = BcdToByte(hunkBuf[offset + 14]);
                if (minute > 90 || second > 59 || frameVal > 74) continue;

                var aba = (uint)((minute * 60 + second) * 75 + frameVal);
                var lba = aba >= 150 ? aba - 150 : 0;
                track.StartLba = lba >= scan ? lba - scan : 0;
                found = true;
                break;
            }

            if (!found)
            {
                track.StartLba = 0;
            }
        }
    }

    private static byte BcdToByte(byte bcd)
    {
        return (byte)((bcd >> 4) * 10 + (bcd & 0x0F));
    }

    /// <summary>
    /// Releases all resources used by the <see cref="SectorReader"/>, including the cached hunk buffer.
    /// </summary>
    public void Dispose()
    {
        ReturnCachedHunk();
        GC.SuppressFinalize(this);
    }
